export const DICTIONARIES = { fr, en };
// A numeric `count` var selects `<key>.<plural category>` when that form exists
// (e.g. 'mastery.total.one'); the bare key holds the plural ("other") form.
const PLURAL_RULES = { fr: new Intl.PluralRules('fr'), en: new Intl.PluralRules('en') };
export function validateDictionaries() {
  const a = Object.keys(fr).sort(),
    b = Object.keys(en).sort();
  return a.length === b.length && a.every((key, i) => key === b[i]);
}
export function createI18n(initial = 'fr') {
  let lang = initial === 'en' ? 'en' : 'fr';
  return {
    get lang() {
      return lang;
    },
    setLang(value) {
      lang = value === 'en' ? 'en' : 'fr';
      document.documentElement.lang = lang;
    },
    t(key, vars = {}) {
      const fallbackLang = lang === 'fr' ? 'en' : 'fr';
      const lookup = (id) => DICTIONARIES[lang][id] ?? DICTIONARIES[fallbackLang][id];
      const form = typeof vars.count === 'number' ? PLURAL_RULES[lang].select(vars.count) : null;
      const value = (form && lookup(`${key}.${form}`)) ?? lookup(key) ?? `⟦${key}⟧`;
      return value.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`));
    },
  };
}
